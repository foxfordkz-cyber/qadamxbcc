def language(value: object) -> str:
    return "kk" if value == "kk" else "ru"


def buttons(rows: list[tuple[str, str]]) -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(
        inline_keyboard=[
            [InlineKeyboardButton(text=label, callback_data=action)] for label, action in rows
        ]
    )


async def display(message: Message, text: str, markup: InlineKeyboardMarkup, *, edit: bool) -> None:
    if not edit:
        await message.answer(text, reply_markup=markup, parse_mode=None)
        return
    try:
        await message.edit_text(text, reply_markup=markup, parse_mode=None)
    except TelegramBadRequest:
        # Deleted or unchanged menu: do not convert an edit failure to another send.
        return


async def configure_commands(bot: Bot) -> None:
    """Called once per authorized polling startup, after acquiring the singleton lock."""
    try:
        async with asyncio.timeout(15):
            for lang in ("", "ru", "kk"):
                await bot.set_my_commands(
                    [
                        BotCommand(command=k, description=v[lang == "kk"])
                        for k, v in COMMANDS.items()
                    ],
                    scope=BotCommandScopeAllPrivateChats(),
                    language_code=lang,
                )
            await bot.set_chat_menu_button(menu_button=MenuButtonCommands())
    except (TelegramAPIError, TimeoutError):
        # Commands remain available as text and inline buttons; no retry storm or raw errors.
        logging.getLogger("bcc.integrations").warning("TELEGRAM_COMMAND_MENU_UNAVAILABLE")
